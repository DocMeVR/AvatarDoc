import { stripBom } from './strings.mjs';

const normalise = (text) => stripBom(text).replace(/\r\n/g, '\n');

function frontmatter(title, description, source, extra = []) {
  return [
    '---',
    `title: ${title}`,
    `description: ${description}`,
    ...extra,
    '---',
    `<!-- Generated by scripts/generate.mjs from ${source}. Do not edit; edit the source. -->`,
    '',
  ].join('\n');
}

function dropFirstHeading(text) {
  return text.replace(/^\s*# [^\n]*\n+/, '');
}

export function changelogPage(source, sourceName) {
  return frontmatter('Changelog', 'What changed in each AvatarDoc release.', sourceName) + '\n' + dropFirstHeading(normalise(source));
}

function splitRow(line) {
  const inner = line.trim().replace(/^\|/, '').replace(/\|$/, '');
  return inner.split(/(?<!\\)\|/).map((cell) => cell.trim());
}

export function glossaryPage(source, sourceName) {
  const lines = normalise(source).split('\n');
  const start = lines.findIndex((l) => l.startsWith('## '));
  const out = [
    'The words AvatarDoc uses for VRChat and Unity things. Each thing has one name everywhere in the tool and in these pages.',
    '',
  ];
  for (const line of lines.slice(start)) {
    if (line.startsWith('|')) {
      const cells = splitRow(line);
      if (cells.every((c) => /^:?-+:?$/.test(c))) out.push('|---|---|');
      else out.push(`| ${cells[0]} | ${cells[cells.length - 1]} |`);
    } else {
      out.push(line);
    }
  }
  return frontmatter('Glossary', 'The words AvatarDoc uses, and the words it keeps in English.', sourceName) + '\n' + out.join('\n');
}

export function translatePage(source, sourceName) {
  const text = dropFirstHeading(normalise(source)).replace(
    /\]\(glossary\.md(#[^)]*)?\)/g,
    (_, hash) => `](../../how-it-works/glossary/${hash || ''})`,
  );
  return frontmatter('Help translate', 'Add a language to AvatarDoc, or keep one up to date.', sourceName) + '\n' + text;
}

export function messagesPage(body, sourceName) {
  const intro =
    'Every warning, error and note AvatarDoc shows is listed here, with the exact English text. A name or a number in the text shows as … here.';
  return (
    frontmatter('Messages', 'Every warning, error and note AvatarDoc shows, with what to do.', sourceName, ['tableOfContents:', '  maxHeadingLevel: 2']) +
    '<!-- Notes come from src/data/message-notes.yml, read as key: text lines only (no YAML lists, quotes or multi-line values). -->\n\n' +
    intro +
    '\n\n' +
    body
  );
}

export function parseNotes(source) {
  const notes = {};
  for (const line of normalise(source).split('\n')) {
    const m = /^(ad\.[\w.]+):\s*(.+?)\s*$/.exec(line);
    if (m) notes[m[1]] = m[2];
  }
  return notes;
}
