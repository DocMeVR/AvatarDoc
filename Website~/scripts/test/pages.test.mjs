import test from 'node:test';
import assert from 'node:assert/strict';
import { changelogPage, glossaryPage, translatePage, parseNotes } from '../lib/pages.mjs';

test('the changelog loses its own first heading and gains frontmatter', () => {
  const md = changelogPage('# Changelog\n\n## [0.3.0](x) (2026-10-10)\n\n* a\n', 'CHANGELOG.md');
  assert.match(md, /\n<!-- Generated by scripts\/generate\.mjs from CHANGELOG\.md\./);
  assert.match(md, /\ntitle: Changelog\n/);
  assert.doesNotMatch(md, /^# Changelog/m);
  assert.match(md, /## \[0\.3\.0\]/);
});

const glossary = [
  '# AvatarDoc glossary',
  '',
  'Intro.',
  '',
  '## VRChat and Unity terms',
  '',
  '| English | Japanese | Simplified Chinese | Note |',
  '|---|---|---|---|',
  '| Avatar | アバター | Avatar | Chinese keeps it. |',
  '| Menu | メニュー | 菜单 | |',
  '',
  '## Kept in English',
  '',
  'These stay in English in every language:',
  '',
  '- AvatarDoc',
  '- VRChat',
  '',
].join('\n');

test('the glossary keeps English and Note and the kept list', () => {
  const md = glossaryPage(glossary, 'Docs~/glossary.md');
  assert.match(md, /\ntitle: Glossary\n/);
  assert.match(md, /\| English \| Note \|/);
  assert.match(md, /\| Avatar \| Chinese keeps it\. \|/);
  assert.match(md, /\| Menu \| {1,2}\|/);
  assert.doesNotMatch(md, /アバター|菜单/);
  assert.match(md, /- VRChat/);
});

test('the translate page points glossary links at the site', () => {
  const md = translatePage('# Translating AvatarDoc\n\nSee [the glossary](glossary.md) and [x](glossary.md#kept).\n', 'Docs~/translating.md');
  assert.match(md, /\ntitle: Help translate\n/);
  assert.match(md, /\]\(\.\.\/\.\.\/how-it-works\/glossary\/\)/);
  assert.match(md, /\]\(\.\.\/\.\.\/how-it-works\/glossary\/#kept\)/);
});

test('parseNotes reads key: text lines only', () => {
  assert.deepEqual(parseNotes('# c\n{}\nad.warn.a: Do this.\n\nad.warn.b: And: that.\n'), { 'ad.warn.a': 'Do this.', 'ad.warn.b': 'And: that.' });
  assert.deepEqual(parseNotes('{}\n'), {});
});
